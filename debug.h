#ifndef _DEBUG_H_
#define _DEBUG_H_

#include "stdint.h"

// ============================================================================
// ASSERT — 「この条件は必ず成り立っているはず」を確認するためのマクロ
// ============================================================================
// 使い方: ASSERT(条件式)
// 条件式が偽(0)だった場合、error_check()(debug.c)を呼び出し、
// どのファイルの何行目でこのASSERTが失敗したかを画面に表示してから、
// 無限ループでCPUを止める。
//
// 例えば ASSERT(x > 0) と書けば、「ここに来た時点でxは必ず0より
// 大きいはずだ」という前提をコードの中に書き残せる。もし実際には
// そうでなかった場合(バグがある場合)、その場で気づける。
// 何もエラーチェックをしないと、バグの影響が別の場所まで伝わって
// から、全然関係なさそうな場所で謎のクラッシュが起きる、ということに
// なりやすい。ASSERTは「おかしくなった、まさにその場所」で早めに
// 止めるための道具。
//
// do { ... } while (0) で全体を囲んでいるのは、C言語のマクロにおける
// 定番のテクニック。こうしておくと、
//   if (何か) ASSERT(x); else ...;
// のように、他のif文の中に埋め込んで書いても、普通の1つの文として
// 扱われ、;の付け方などで意図しない構文エラーを起こさずに済む。
#define ASSERT(e) do {                      \
        if (!(e))                           \
            error_check(__FILE__,__LINE__); \
} while (0)

// error_check — ASSERT失敗時に実際に呼ばれる関数(debug.c)。
// file: __FILE__マクロで自動的に埋め込まれる、このファイルの名前
// line: __LINE__マクロで自動的に埋め込まれる、ASSERTが書かれていた行番号
void error_check(char *file, uint64_t line);

#endif
