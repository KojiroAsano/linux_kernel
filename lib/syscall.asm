; ============================================================================
; syscall.asm(ユーザーランド版) — システムコールの呼び出しスタブ
; ============================================================================
; ユーザープログラムがカーネルの機能(画面表示・スリープ・終了など)を
; 使うための窓口。どの関数も「引数をスタック上に並べ、システムコール
; 番号をEAXに入れて、int 0x80を実行する」という同じパターンをしている。
; カーネル側(trap.c/syscall.c)の呼び出し規約は:
;   RAX = システムコール番号
;   RDI = 引数の個数
;   RSI = 引数配列(int64_t[])へのポインタ
; なので、ここではスタック上に引数を積んで、そのアドレスをRSIとして渡す。
; ============================================================================

section .text
global writeu
global sleepu
global exitu
global waitu
global keyboard_readu
global get_total_memoryu
global killu

; ============================================================================
; int writeu(char *buffer, int size) — buffer先頭sizeバイトを画面へ出力する
; ============================================================================
; RDI=buffer, RSI=size(System V AMD64 ABIでのC言語の引数)。
; これをシステムコール引数配列[buffer, size]としてスタックに積み直し、
; RSI(引数配列へのポインタ)・RDI(引数の個数=2)・EAX(システムコール
; 番号0=sys_write)を設定してint 0x80する。
writeu:
    sub rsp,16       ; 引数2個(8バイト×2)分のスタック領域を確保
    xor eax,eax       ; EAX=0(システムコール番号0=sys_write)

    mov [rsp],rdi      ; argptr[0] = buffer
    mov [rsp+8],rsi     ; argptr[1] = size

    mov rdi,2            ; 引数の個数=2
    mov rsi,rsp            ; RSI = 引数配列(今積んだ場所)へのポインタ
    int 0x80                ; カーネルへ処理を依頼する

    add rsp,16        ; 確保したスタック領域を戻す
    ret

; ============================================================================
; void sleepu(uint64_t ticks) — 指定ティック数だけ眠る
; ============================================================================
sleepu:
    sub rsp,8        ; 引数1個分のスタック領域を確保
    mov eax,1         ; EAX=1(システムコール番号1=sys_sleep)

    mov [rsp],rdi      ; argptr[0] = ticks
    mov rdi,1            ; 引数の個数=1
    mov rsi,rsp           ; RSI = 引数配列へのポインタ

    int 0x80

    add rsp,8
    ret

; ============================================================================
; void exitu(void) — このプロセスを終了する
; ============================================================================
exitu:
    mov eax,2    ; EAX=2(システムコール番号2=sys_exit)
    mov rdi,0     ; 引数の個数=0

    int 0x80

    ret

; ============================================================================
; void waitu(void) — 終了済みプロセスの回収役として居座る
; ============================================================================
waitu:
    mov eax,3    ; EAX=3(システムコール番号3=sys_wait)
    mov rdi,0     ; 引数の個数=0

    int 0x80

    ret

; ============================================================================
; unsigned char keyboard_readu(void) — キー入力を1文字取得する(無ければ待つ)
; ============================================================================
keyboard_readu:
    mov eax,4    ; EAX=4(システムコール番号4=sys_keyboard_read)
    xor edi,edi   ; 引数の個数=0

    int 0x80

    ret

; ============================================================================
; int get_total_memoryu(void) — 使用可能な物理メモリの合計(MB)を取得する
; ============================================================================
get_total_memoryu:
    mov eax,5    ; EAX=5(システムコール番号5=sys_get_total_memory)
    xor edi,edi   ; 引数の個数=0

    int 0x80

    ret

; ============================================================================
; int killu(int pid) — 指定したPIDのプロセスを強制終了させる
; ============================================================================
; 戻り値は0=成功、-1=失敗(該当PIDが無い)。自分自身のPIDを指定した
; 場合は、この呼び出し自体がプロセスの終了で戻ってこない。
killu:
    sub rsp,8        ; 引数1個分のスタック領域を確保
    mov eax,6         ; EAX=6(システムコール番号6=sys_kill)

    mov [rsp],rdi      ; argptr[0] = pid
    mov rdi,1            ; 引数の個数=1
    mov rsi,rsp           ; RSI = 引数配列へのポインタ

    int 0x80

    add rsp,8
    ret
