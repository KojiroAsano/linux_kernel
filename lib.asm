; ============================================================================
; lib.asm — memset/memmove/memcpy/memcmpの実体(アセンブリ実装)
; ============================================================================
; C言語の呼び出し規約(System V AMD64 ABI)では、関数の引数は
; 1個目=RDI, 2個目=RSI, 3個目=RDX(4個目以降はRCX,R8,R9...)という
; レジスタに入れて渡される。この規約を前提に、C側の関数宣言
; (lib.h)の引数名を、対応するレジスタに置き換えて読むとわかりやすい。
; ============================================================================

section .text
global memset
global memmove
global memcpy
global memcmp

; ============================================================================
; memset(void *buffer, char value, int size)
; ============================================================================
; buffer(RDI)の先頭からsize(RDX)バイトを、全部value(RSI下位8bit)で埋める。
memset:
    cld ; Clear direction flag
        ; DF(方向フラグ)を0にする=アドレスが「増える」向きに処理する、
        ; という指定。rep系の命令(stosb/movsb/cmpsbなど)は、このDFを
        ; 見て「RDI/RSIを+1していくか、-1していくか」を決める。
    mov ecx, edx   ; rep stosbの繰り返し回数(RCX)に、sizeをセットする
    mov al, sil    ; valueの値(RSIの下位8bit)をALへ。stosbはALの値を書き込む
    rep stosb      ; 「ALの値をRDIが指す場所へ書き込み、RDIを+1、
                   ;  RCXを-1」を、RCXが0になるまで繰り返す
    ;rdi buffer, rsi value, rdx size
    ret   ; 呼び出し元へ戻る

; ============================================================================
; int memcmp(const void *s1, const void *s2, int size)
; ============================================================================
; s1(RDI)とs2(RSI)の先頭size(RDX)バイトを比較する。
; 【注意】この実装は、全部一致していれば1を、1箇所でも違えば0を返す。
; C言語の標準ライブラリのmemcmp(一致なら0、不一致なら0以外)とは
; 戻り値の意味が逆になっているので、もしこの関数を実際に使う時は
; この向きに気をつけること(標準のmemcmpだと思って
; if (memcmp(a,b,n) == 0) のように書くと、条件が丸ごと逆になる)。
; 現時点ではこの関数はまだどこからも呼ばれていない。
memcmp:
    cld             ; DF=0(前進方向)にしておく
    xor eax, eax    ; 戻り値(EAX)をいったん0にしておく
    mov ecx, edx    ; 比較するバイト数
    repe cmpsb      ; 「RDIとRSIが指す1バイトを比較し、両方を+1、RCXを-1」を、
                    ; 「一致していて、かつRCXが0でない」間繰り返す。
                    ; つまり、不一致が見つかった時点か、最後まで
                    ; 一致し続けた場合のどちらかで止まる。
    setz al         ; 直前の比較結果がZF=1(一致)だったならAL=1、
                    ; そうでなければAL=0
    ret   ; 呼び出し元へ戻る(戻り値はAL/EAX)

; ============================================================================
; memcpy(void *dest, const void *src, int size) / memmove(同じ引数)
; ============================================================================
; memcpyとmemmoveは全く同じコードを共有している。通常memcpyは
; 「範囲が重なっていない前提で、単純にコピーするだけ」の軽量版、
; memmoveは「範囲が重なっていても正しくコピーできる」安全版、と
; 役割が分かれることが多いが、ここでは常に「重なりチェック」を
; 行ってから適切な向きでコピーする、常に安全な実装を両方の名前で
; 共有している。
memcpy:
memmove:
    cld
    ; --- 範囲が重なっているかどうかの判定 ---
    ; src(RSI)がdest(RDI)以降にあるなら、そもそも重なっていても
    ; 前から後ろへコピーして問題ない(.copyへ)。
    cmp rsi, rdi   ; srcとdestを比較
    jae .copy      ; src >= destなら、そのまま前から後ろへコピーしてOK
    ; srcの終端(RSI+size)がdestの開始より前か同じなら、
    ; 重なっていないので、同じく前から後ろへコピーして良い(.copyへ)。
    mov r8, rsi    ; R8=srcの開始アドレス
    add r8, rdx    ; R8=srcの終端アドレス(src+size)
    cmp r8, rdi    ; srcの終端とdestを比較
    jbe .copy      ; 重なっていなければ、前から後ろへコピーしてOK

.overlap:
    ; ここに来るのは「destがsrcより後ろにあり、かつ範囲が重なっている」
    ; 場合。この状況で前から後ろへコピーすると、まだコピーしていない
    ; 部分を、コピー中に上書きしてしまう恐れがある。そこで、
    ; あえて「後ろから前へ」コピーする向きに切り替える。
    std            ; DF=1にする(rep movsbがRDI/RSIを-1ずつ進めるようになる)
    add rdi, rdx   ; RDIを範囲の「末尾の次」へ移動させる
    add rsi, rdx   ; RSIも同様に「末尾の次」へ移動させる
    sub rdi, 1     ; std指定時は「末尾のバイト」から書き始める必要があるので、
    sub rsi, 1     ; ちょうど末尾を指すよう1バイト分戻す

.copy:
    mov ecx, edx    ; コピーするバイト数
    rep movsb       ; 「RSIが指すバイトをRDIへコピーし、両方をDFの向きに1ずつ進める」
                    ; を、RCXが0になるまで繰り返す
    cld             ; 呼び出し元に「DFは必ず0(前進)」という一般的な前提を
                    ; 壊さず返すため、後片付けとして必ず0に戻しておく
    ret   ; 呼び出し元へ戻る
