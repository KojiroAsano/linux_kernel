; ============================================================================
; boot.asm — MBR(マスターブートレコード)ブートセクタ
; ============================================================================
; このファイルはPCの電源を入れた直後、BIOSが一番最初に読み込んで実行する
; たった512バイトのプログラムです。BIOSはディスクの先頭セクタ(セクタ0、
; 512バイト)を物理アドレス0x7c00にそのまま読み込み、そこへジャンプします。
; だから下の[ORG 0x7c00]は「このコードは0x7c00番地に置かれる前提で
; アドレス計算してね」とアセンブラに伝えるためのものです。
;
; このファイルの役目はただ1つ：
;   ディスクからloader.bin(次の段階のプログラム)を読み込んで、そこへ
;   処理を引き継ぐこと。
; 512バイトしか使えないので、できることは最小限です。実際にOSっぽい
; 処理をするのはこの後のloader.asm・kernel.asmです。
; ============================================================================

[BITS 16]      ; 電源投入直後のCPUは16bit「リアルモード」で動く。ここから
                ; しばらくは、8086時代と同じ16bitの命令しか使えない。
[ORG 0x7c00]    ; このプログラムが実際に置かれるメモリ番地(BIOSの仕様で固定)。

; --- ビルド時に渡されるディスクサイズ ---
; TOTAL_SECTORSは「このboot.img全体が何セクタあるか」を表す値。
; build.shがnasmを呼ぶときに -DTOTAL_SECTORS=<実際の値> という形で渡して
; くれる。もし渡されなかった場合(このファイル単体でアセンブルした場合など)
; は、下のフォールバック値110を使う。この値は末尾のパーティションテーブル
; の表示にだけ使われ、ブート処理そのものには影響しない。
%ifndef TOTAL_SECTORS
%define TOTAL_SECTORS 110   ; build.shから-Dで渡されなかった場合のフォールバック値
%endif

start:
    ; 画面に'B'の1文字を出す。BIOSのINT 10h(ビデオサービス)のAH=0x0eは
    ; 「テレタイプ出力」と呼ばれる機能で、AL に入れた1文字をカーソル位置に
    ; 表示してカーソルを1つ進めてくれる。ここから先、各段階(boot→loader→
    ; kernel)の節目で1文字ずつ表示することで、「今どこまで進んだか」を
    ; 目で見て確認できるようにしている。もし途中で止まったら、最後に
    ; どの文字が表示されているかを見れば、どの段階で失敗したか分かる。
    mov ah, 0x0e
    mov al, 'B'     ; 'B' = Boot(このファイルまで来た、という印)
    int 0x10

    ; --- セグメントレジスタとスタックの初期化 ---
    ; リアルモードのメモリアドレスは「セグメント:オフセット」という2つの
    ; 値の組で決まる。BIOSがどんな値でセグメントレジスタ(DS/ES/SS)を
    ; 残しているか分からないので、まず全部0にしておいて、以降のアドレス
    ; 計算を単純化する(セグメント=0にすれば、オフセットの値=物理アドレス
    ; になって分かりやすい)。
    cli             ; 設定中に割り込みが入ると危険なので一時的に禁止
    xor ax, ax      ; ax = 0 (xorで自分自身とXORすると必ず0になる、定番の書き方)
    mov ds, ax      ; データセグメント = 0
    mov es, ax      ; エクストラセグメント = 0
    mov ss, ax      ; スタックセグメント = 0
    mov sp, 0x7c00  ; スタックポインタ = 0x7c00
                    ; このプログラム自身が0x7c00から始まっているので、
                    ; スタックはそこから下(低いアドレス)へ伸びていく。
                    ; つまりスタックとプログラム本体がぶつからない。
    sti             ; 初期化が終わったので割り込みを許可に戻す

    ; BIOSはブート時、DLレジスタに「どのディスクから起動したか」を表す
    ; ドライブ番号を入れてくれる。後でディスク読み込みに使うので、
    ; メモリ上の変数DriveIdに保存しておく(レジスタは後でどんどん
    ; 上書きされるので、覚えておきたい値は変数に退避するのが基本)。
    mov [DriveId], dl

; --- 拡張INT13チェック ---
; 大昔のBIOSディスク読み込み(INT 13h, AH=0x02)は「CHS」というシリンダ/
; ヘッド/セクタ方式で、大きなディスクを扱えない。現代的な「LBA拡張」
; 機能が使えるかどうかを、実際に使う前に確認しておく。
    mov ah, 0x41    ; AH=0x41: 拡張INT13対応チェック機能
    mov bx, 0x55aa  ; この値を入れて呼ぶのが仕様上の決まり
    int 0x13
    jc disk_error   ; CF(キャリーフラグ)が立っていたら「非対応」→エラー処理へ
    cmp bx, 0xaa55  ; 対応していればBXが0xaa55に書き換わって返ってくる
    jne disk_error  ; 違う値なら何かおかしいのでエラー処理へ

; --- loader 読み込み ---
; ここから先、次の段階のプログラム(loader.bin)をディスクから読み込む。
; 拡張INT13(AH=0x42)は、「DAP」というメモリ上の小さな構造体で
; パラメータを渡す方式になっている。DAPの中身は下のコメントの通り。
    mov si, dap
    ; DAP(Disk Address Packet)の各フィールドを埋めていく。
    ; siがDAPの先頭アドレスを指しているので、[si+オフセット]で
    ; 各フィールドを指定する。
    mov word [si], 0x10        ; オフセット0: このDAP自体のサイズ(固定で16バイト)
    mov word [si+2], 5         ; オフセット2: 読み込むセクタ数。
                                ; loader.bin用に余裕を持って5セクタ(2560バイト)
                                ; 確保している(実際のloader.binはもっと小さい)。
    mov word [si+4], 0x7e00    ; オフセット4: 読み込み先のオフセットアドレス
    mov word [si+6], 0x0000    ; オフセット6: 読み込み先のセグメント
                                ; セグメント0:オフセット0x7e00 = 物理0x7e00番地。
                                ; ちょうど今このboot.asm(512バイト)の直後。
    mov dword [si+8], 1        ; オフセット8: 読み込み開始LBA(論理ブロック番号)。
                                ; LBA0はこのboot.asm自身が入っているセクタなので、
                                ; その次のLBA1から読む。
    mov dword [si+12], 0       ; オフセット12: LBAの上位32bit(今回は使わないので0)

    mov dl, [DriveId]  ; さっき保存しておいたドライブ番号を復元
    mov ah, 0x42       ; AH=0x42: 拡張INT13、DAPを使ったディスク読み込み
    int 0x13
    jc disk_error      ; 読み込み失敗ならエラー処理へ

; --- loaderへ ---
    mov dl, [DriveId]   ; loader.asm側もドライブ番号を使うので、DLに入れたまま渡す
    jmp 0x0000:0x7e00   ; たった今読み込んだloader.binの先頭(0x7e00番地)へジャンプ。
                        ; ここから先はloader.asmの世界。このboot.asmの役目は
                        ; ここで終わり。

; ============================================================================
; エラー処理
; ============================================================================
; 拡張INT13が使えない、あるいはディスク読み込みに失敗した場合はここに来る。
; エラーメッセージを画面に表示して、そのままCPUを停止させる。
disk_error:
    ; BIOSのINT 10h、AH=0x13(文字列表示機能)を使ってMessageの内容を
    ; まとめて表示する。1文字ずつint 0x10を呼ぶより効率的。
    mov ah,0x13
    mov al,1        ; 表示モード: カーソル位置更新あり、属性は下のBXで指定
    mov bx,0xa       ; 文字の属性(色)。0xa = 緑色っぽい明るい色
    xor dx,dx        ; 表示開始位置(行0、列0)
    mov bp,Message   ; 表示する文字列の先頭アドレス
    mov cx,MessageLen  ; 表示する文字数
    int 0x10

hang:
    ; これ以上できることは無いので、CPUを停止させたままループする。
    ; hltは「次の割り込みが来るまでCPUを休ませる」命令。割り込みが来る
    ; たびに一瞬起きてまたjmp hangでhltに戻る、を延々繰り返す。
    hlt
    jmp hang

; ============================================================================
; データ領域(変数・文字列など)
; ============================================================================
DriveId db 0            ; BIOSから教えてもらったドライブ番号を保存する変数(1バイト)
dap times 16 db 0        ; DAP(Disk Address Packet)用に16バイト確保。中身は
                         ; 上の「loader 読み込み」のところで書き込む。
Message:    db "We have an error in boot process"
MessageLen: equ $-Message  ; equ $-Message は「今のアドレス - Messageのアドレス」、
                            ; つまり文字列の長さを自動計算してくれる書き方。
                            ; 文字列を書き換えても長さを手で数え直さなくて済む。

; ============================================================================
; MBR固定フォーマット部分(0x1BEから始まるパーティションテーブル)
; ============================================================================
; MBR(先頭セクタ)は512バイト全体のうち、末尾の66バイトが仕様で決まった
; 固定フォーマットになっている。BIOSはこの部分を直接は使わないが、
; 一部のツール(fdiskなど)がこのディスクを見たときに「一応それらしい
; パーティション情報がある」ように見せるためのもの。自作のこの
; ブートローダー自身は、このパーティションテーブルを一切読まない。

; times (0x1be-($-$$)) db 0
; 「現在のアドレスから0x1be番地まで、0で埋める」という意味。
; $  = 今アセンブルしている位置のアドレス
; $$ = このセクション(このファイル)の先頭アドレス
; ($-$$) で「ファイル先頭からの相対位置」が求まるので、
; 0x1beまでの残りバイト数だけ0を詰めている。
times (0x1be-($-$$)) db 0

    ; ここから1つ分のパーティションテーブルエントリ(16バイト)。
    db 80h              ; ブートフラグ。0x80 = 「このパーティションが
                         ; アクティブ(起動用)」という意味の慣習的な値。
    db 0,2,0             ; 開始位置のCHS(シリンダ/ヘッド/セクタ)。
                         ; 今どきはLBAを使うので、ここは形式的な値。
    db 0f0h               ; パーティションタイプ。標準の値ではなく、
                         ; 「独自OS」であることを示す適当な値。
    db 0ffh,0ffh,0ffh      ; 終了位置のCHS。0xFFFFFFは「CHSでは表現しきれない
                         ; ほど大きい、LBAの値を見てね」という意味の慣習値。
    dd 1                  ; このパーティションの開始LBA(セクタ1から、
                         ; つまりMBR自身の直後から)。
    dd (TOTAL_SECTORS-1)  ; このパーティションのサイズ(セクタ数)。
                          ; ディスク全体(TOTAL_SECTORS)からMBRの1セクタ分を
                          ; 引いた値。実際の起動処理には使われない、
                          ; あくまで見た目を実際のサイズに合わせるための値。

    times (16*3) db 0    ; 残り3つ分のパーティションテーブルエントリ
                         ; (16バイト×3 = 48バイト)は未使用なので全部0。

    ; MBRの最後の2バイトは必ずこの値でなければならない、という仕様。
    ; BIOSはこの2バイトを見て「これは起動可能なディスクだ」と判断する。
    ; もしこの値が無いと、BIOSは "No bootable device" のようなエラーを
    ; 出してこのプログラムを一切実行してくれない。
    db 0x55
    db 0xaa

; (下の2行は昔の書き方の名残でコメントアウトされたまま残っている。
;  上のdb 0x55/db 0xaaと同じ意味の、別の書き方の例)
; times 510-($-$$) db 0
; dw 0xAA55
