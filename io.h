#ifndef _IO_H_
#define _IO_H_

#include "stdint.h"

// ============================================================================
// io.h — I/Oポートへの読み書き(trap.asmに実体がある)
// ============================================================================
// x86ではメモリとは別に「I/Oポート」という、周辺機器(PIC・PIT・
// キーボードコントローラ・ATAディスクコントローラなど)とやり取り
// するための、番号で指定するアドレス空間がある。in/out命令でしか
// 触れないので、C言語からはこれらの薄いラッパー関数を通して使う。
// keyboard.c(ポート0x60)・ata.c(ポート0x1F0-0x1F7)の両方が使う、
// 汎用の部品。
unsigned char in_byte(uint16_t port);              // 指定ポートから1バイト読む
void out_byte(uint16_t port, uint8_t value);         // 指定ポートへ1バイト書き込む
uint16_t in_word(uint16_t port);                       // 指定ポートから2バイト(1ワード)読む
void out_word(uint16_t port, uint16_t value);            // 指定ポートへ2バイト(1ワード)書き込む

#endif
