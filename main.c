// ============================================================================
// main.c — カーネルのC言語側の入口
// ============================================================================
// kernel.asmが、CPUをロングモードへ移行させ、GDT/TSS/PIC/PITなどの
// 下ごしらえを終えた後に呼び出す、最初のC言語の関数がKMain()。
// ここから先は、アセンブリではなくC言語で「カーネルとして何をするか」を
// 組み立てていく。
// ============================================================================

#include "trap.h"     // init_idt(), enable_interrupts(), enter_usermode() など
#include "print.h"    // printk()
#include "debug.h"     // ASSERT()
#include "memory.h"     // init_memory()

// kernel.asmのUserEntry/UserStackTopラベルを、C言語側から「配列」として
// 参照するための宣言。実際には配列ではなく、それぞれ「その名前のラベルが
// メモリ上のどこにあるか」というアドレスを表す(C言語でよく使われる、
// アセンブリのラベルをCから参照するときの定番の書き方)。
extern char UserEntry[];     // kernel.asm側のリング3デモコード
extern char UserStackTop[];  // kernel.asm側のリング3デモ用スタック

void KMain(void)
{
   char *string = "Hello and Welcome";
   int64_t value = 0x123456789ABCD;  // 動作確認用のテスト値(printkの%x確認に使う)

   // --------------------------------------------------------------------
   // 割り込み関連の初期化
   // --------------------------------------------------------------------
   init_idt();            // IDT(割り込み記述子テーブル)を組み立ててCPUに登録する。
                          // この時点ではまだ割り込みはCPUレベルで禁止されたまま
                          // (loader.asmのcliが効いている)。
   enable_interrupts();  // IDT/PIC/PITは設定済みなのでここで初めて割り込みを許可する
                          // (sti)。この行を境に、タイマー割り込み(IRQ0)が
                          // 実際にCPUへ届くようになる。

   // --------------------------------------------------------------------
   // メモリ管理の初期化
   // --------------------------------------------------------------------
   init_memory();   // BIOSから受け取ったメモリマップ(e820)を解析して、
                    // どこが使える空きメモリかを表示する(memory.c参照)。

   // --------------------------------------------------------------------
   // 動作確認用の表示
   // --------------------------------------------------------------------
   printk("%s\n", string);
   printk("This value is equal to %x", value);   // printkの%x(16進数表示)が
                                                  // 正しく動くかの確認表示
   // ASSERT(0);
   // ↑ わざと必ず失敗するアサーション。ASSERT(0)は「0が真であること」を
   // 確認しようとするが、0は常に偽なので、これを有効にすると必ず
   // error_check()(debug.c)が呼ばれ、画面にエラーメッセージを出して
   // 停止する。ASSERT/error_checkの仕組み自体が正しく動くかを確認したい
   // 時だけ、この行のコメントを外して使う。普段はコメントアウトしたまま
   // にしておく(有効のままだと、この下のenter_usermode()まで
   // 到達できなくなる)。

   // --------------------------------------------------------------------
   // リング3(ユーザーモード)のデモへ処理を渡す
   // --------------------------------------------------------------------
   // ここまでの初期化・確認表示が全部終わったら、最後にリング3への
   // 切り替えを行う。enter_usermode()は内部でiretqを使ってジャンプする
   // ため、この関数呼び出しから普通に戻ってくることはない
   // (呼び出した時点でC言語の制御はここで終わり、以降はkernel.asmの
   // UserEntry:がリング3で動き続ける)。
   enter_usermode((uint64_t)UserEntry, (uint64_t)UserStackTop);  // ここから戻ってこない
}
