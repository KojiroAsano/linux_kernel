// ============================================================================
// main.c — カーネルのC言語側の入口
// ============================================================================
// kernel.asmが、CPUをロングモードへ移行させ、GDT/TSS/PIC/PITなどの
// 下ごしらえを終えた後に呼び出す、最初のC言語の関数がKMain()。
// ここから先は、アセンブリではなくC言語で「カーネルとして何をするか」を
// 組み立てていく。
// ============================================================================

#include "trap.h"     // init_idt() など
#include "print.h"    // printk()
#include "memory.h"   // init_memory(), init_kvm()
#include "process.h"  // init_process(), launch()
#include "syscall.h"  // init_system_call()

// ============================================================================
// KMain — カーネルの初期化を順番に行い、最後にスケジューラへ制御を渡す
// ============================================================================
void KMain(void)
{
   // --------------------------------------------------------------------
   // 割り込み関連の初期化(IDTの組み立てのみ。有効化はまだしない)
   // --------------------------------------------------------------------
   init_idt();   // IDT(割り込み記述子テーブル)を組み立ててCPUに登録する。
                // この時点ではまだ割り込みはCPUレベルで禁止されたまま
                // (loader.asmのcliが効いている)。

   // --------------------------------------------------------------------
   // メモリ管理の初期化
   // --------------------------------------------------------------------
   init_memory();   // BIOSから受け取ったメモリマップ(e820)を解析して、
                    // どこが使える空きメモリかを表示する(memory.c参照)。
   init_kvm();      // 自前のページテーブルを組み立てて実際に切り替える(memory.c参照)。

   // --------------------------------------------------------------------
   // システムコール・プロセス管理の初期化
   // --------------------------------------------------------------------
   init_system_call();   // システムコール番号→実装関数のテーブルを組み立てる(syscall.c)
   init_process();         // loader.asmが読み込んでおいた3本のユーザープログラムを、
                           // それぞれ独立したプロセスとして作る(process.c)。

   // --------------------------------------------------------------------
   // 最初のプロセスへ制御を渡す
   // --------------------------------------------------------------------
   // launch()はready_listの先頭のプロセスをリング3のiretqで起動する。
   // そのプロセスのtf->rflagsにはIFビット(割り込み許可)が立っているので、
   // 切り替わった瞬間から割り込みが有効になる(enable_interrupts()を
   // 明示的に呼ぶ必要が無い、process.cのset_process_entry参照)。
   launch();   // ここから戻ってこない
}
