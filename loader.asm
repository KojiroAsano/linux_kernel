; ============================================================================
; loader.asm — リアルモード → プロテクトモード → ロングモード 移行担当
; ============================================================================
; boot.asm(MBR)がこのファイルをディスクのLBA1から読み込み、物理アドレス
; 0x7e00へ配置してジャンプしてくる。このファイルの仕事は大きく4つ:
;
;   1. CPUがロングモード(64bit)に対応しているか確認する
;   2. カーネル本体(kernel.bin)とメモリマップ(e820)をディスク/BIOSから
;      読み込んでおく(まだBIOSが使える16bitモードのうちにやる必要がある)
;   3. A20ラインを有効化する(古いPC互換の1MB制限を解除する)
;   4. リアルモード→32bitプロテクトモード→64bitロングモードの順に
;      CPUのモードを切り替え、最終的にkernel.binへジャンプする
;
; モードが変わるたびに使える命令やメモリの扱い方が変わるので、
; [BITS 16]→[BITS 32]→[BITS 64] とアセンブラへの指示も切り替えていく。
; ============================================================================

[BITS 16]
[ORG 0x7e00]

; --- ビルド時に渡されるカーネルのサイズ ---
; KERNEL_SECTORSは「kernel.binが何セクタ分あるか」を表す値。build.shが
; 実際にkernel.binをビルドした後、そのファイルサイズから自動計算して
; -DKERNEL_SECTORS=<値> という形でnasmに渡してくれる。渡されなかった場合
; (このファイル単体でアセンブルした場合など)は、下のフォールバック値100
; を使う。この値は下の「LoadKernel」(ディスクから読み込む量)と
; 「LongModeStart」(コピーする量)の両方で使われる。1箇所の数字を
; 直せば両方に反映されるので、「読み込む量」と「コピーする量」が
; ズレて片方だけ古い値のまま、という事故を防げる。
%ifndef KERNEL_SECTORS
%define KERNEL_SECTORS 100  ; build.shから-Dで渡されなかった場合のフォールバック値
%endif

start:
    ; --- セグメント・スタックの初期化(boot.asmと同じ考え方) ---
    cli
    xor ax, ax
    mov ds, ax
    mov es, ax
    mov ss, ax
    mov sp, 0x7c00
    sti; enable interrupt for keyboard
    mov [DriveId],dl   ; boot.asmから引き継いだドライブ番号を保存

    ; 進捗確認用に'L'(Loader)を表示。boot.asmの'B'に続いてここまで
    ; 来たことが分かる。
    mov ah, 0x0e
    mov al, 'L'
    int 0x10

    ; ========================================================================
    ; ステップ1: CPUIDでロングモード対応を確認する
    ; ========================================================================
    ; CPUID命令は、EAXに「知りたい情報の種類(リーフ番号)」を入れて呼ぶと、
    ; EAX/EBX/ECX/EDXにその情報が返ってくる、CPUの機能を調べるための命令。
    ; まず0x80000000を渡して「拡張リーフはいくつまで使えるか」を聞く。
    mov eax, 0x80000000
    cpuid
    cmp eax, 0x80000001
    jb NoLongMode   ; 0x80000001未満しか対応していないなら、この先で聞きたい
                    ; 「ロングモード対応か」という情報自体が取得できない

    ; 0x80000001を渡すと、EDXの各ビットに拡張機能の対応状況が入って返る。
    mov eax, 0x80000001
    cpuid
    test edx, (1<<29)      ; LMビット（ロングモード対応）
    jz NoLongMode
    test edx, (1<<26)      ; Page1GBビット（下のブートストラップ用ページテーブルが使用）
    jz NoLongMode
    ; 注: QEMUの-cpu qemu64はデフォルトではPage1GB非対応と申告するため、
    ; build.shのqemu起動オプションに+pdpe1gbを付けて申告を実態(1GBページの
    ; PDPTEを問題なく処理できる)に合わせてある。このチェックを有効にしたまま
    ; QEMUで動かす場合は+pdpe1gbを外さないこと。実機やこのフラグ無しの環境で
    ; 本当に1GBページ非対応のCPUに当たった場合は、ここで正しく検出して止まる。

    jmp skip_ext    ; 両方の機能があると確認できたので、先に進む

NoLongMode:
    ; ロングモードか1GBページのどちらかに非対応だった場合はここに来る。
    ; 'X'を表示して、これ以上進めないことを画面で分かるようにしてから、
    ; 下のNotSupport(エラー処理・停止ループ)へ合流する。
    mov ah, 0x0e
    mov al, 'X'
    int 0x10
    jmp NotSupport

skip_ext:

    ; ========================================================================
    ; ステップ2: カーネル本体をディスクから読み込む
    ; ========================================================================
LoadKernel:

    ; boot.asmの時と同じ、拡張INT13(AH=0x42)用のDAP(Disk Address Packet)
    ; を組み立てる。今回はReadPacketという変数に書き込む。
    mov si,ReadPacket
    mov word[si],0x10             ; DAPのサイズ(固定16バイト)
    mov word[si+2],KERNEL_SECTORS ; 読み込むセクタ数(build.shが計算した値)
    mov word[si+4],0               ; 読み込み先オフセット
    mov word[si+6],0x1000           ; 読み込み先セグメント
                                    ; セグメント0x1000:オフセット0 = 物理0x10000番地。
                                    ; まだ64bitモードではないので、いったんこの
                                    ; 低いアドレスに置いておき、後でロングモードに
                                    ; 入ってから本来の場所(0x200000)へコピーする。
    mov dword[si+8],6              ; 読み込み開始LBA=6。
                                    ; LBA0=boot.asm(1セクタ)、LBA1-5=loader.asm(5セクタ)
                                    ; なので、その続きのLBA6からがkernel.bin。
    mov dword[si+0xc],0            ; LBAの上位32bit(未使用)

    mov dl,[DriveId]
    mov ah,0x42
    int 0x13
    jc  ReadError   ; 読み込み失敗ならエラー処理へ

    ; 進捗確認用に'S'(Success、カーネル読み込み成功)を表示。
    mov ah, 0x0e
    mov al, 'S'
    int 0x10

    ; ========================================================================
    ; ステップ3: BIOSからメモリマップ(e820)を取得する
    ; ========================================================================
    ; カーネルは後で「どこにどれだけ使える(空いている)メモリがあるか」を
    ; 知る必要がある。それを教えてくれるのがBIOSのINT 15h, EAX=0xe820。
    ; 1回の呼び出しで1つの「メモリ領域の情報(開始アドレス・長さ・種類)」
    ; しか返ってこないので、EBXに入る「続きがあるかどうかの印」を見ながら
    ; ループして、全部の領域を取得しきるまで繰り返す。
    ; 取得した情報は物理アドレス0x9008以降にどんどん書き込んでいき、
    ; 0x9000には「何個の領域を取得できたか」という件数を書いておく
    ; (この2つのアドレスは、後でmemory.cのinit_memory()がそのまま読む)。
GetMemInfoStart:
    mov eax, 0xe820
    mov edx, 0x534d4150 ; 'SMAP' という4文字をASCIIコードにした値。
                        ; この機能を呼ぶときの仕様上のお約束(合言葉のようなもの)。
    mov ecx, 20          ; 1回の呼び出しで受け取るバッファのサイズ(20バイト)
    mov dword[0x9000],0  ; 取得件数カウンタを0で初期化
    mov edi, 0x9008       ; 1個目の情報を書き込む先(件数カウンタの直後)
    xor ebx, ebx           ; EBX=0で呼ぶと「最初から」という意味になる
    int 0x15
    jc NotSupport            ; 最初の呼び出しから失敗するなら、この機能自体が
                             ; 使えないということなのでエラー処理へ

GeMemInfo:
    add edi, 20         ; 次に書き込む位置を20バイト分進める
    inc dword[0x9000]    ; 取得件数カウンタを+1
    test ebx, ebx         ; EBXが0になっていたら「これが最後の領域だった」
    jz GetMemDone
    ; まだ続きがあるので、もう1回呼ぶ(EBXは前回の呼び出しが自動で
    ; 「次はここから」という値に更新してくれているので、そのまま使う)
    mov eax, 0xe820
    mov edx, 0x534d4150 ; 'SMAP'
    mov ecx, 20
    int 0x15
    jnc GeMemInfo        ; 成功(CF=0)ならループを続ける

    test ebx, ebx
    jnz GeMemInfo        ; BIOSによってはここで失敗扱い(CF=1)しつつ
                         ; まだ続きがある、という挙動をすることがあるための保険

GetMemDone:
    ; 進捗確認用に'D'(Done、メモリマップ取得完了)を表示。
    mov ah, 0x0e
    mov al, 'D'
    int 0x10

    ; ========================================================================
    ; ステップ4: A20ラインを有効化する
    ; ========================================================================
    ; 大昔のPC(8086)はメモリアドレスが20bitまでしか無く、1MBまでしか
    ; アクセスできなかった。その後CPUが進化して1MBを超えてアクセス
    ; できるようになったが、古いソフトとの互換性のため、電源投入直後は
    ; わざと21bit目(A20)を無視する仕組みが標準で入っている。1MBを超えた
    ; メモリを正しく使うには、これを明示的に解除(有効化)する必要がある。
TestA20:
    ; 有効かどうかの判定方法：セグメント0(=物理0x00000)とセグメント
    ; 0xffff(=物理0xffff0)から少しずらした位置を比べる。A20が無効なら、
    ; 1MBを超えたアドレスは1MB未満の位置に「折り返して」しまうので、
    ; 全く違う場所に書いたはずの値が、同じ場所を指しているように見える。
    mov ax,0xffff
    mov es,ax
    mov word[ds:0x7c00],0xa200      ; 低いアドレス側に試しの値を書く
    cmp word[es:0x7c10],0xa200      ; 高いアドレス側(A20無効なら同じ場所に
                                    ; 見えるはずの位置)を読んで比較
    jne SetA20LineDone              ; 値が違う=すでに有効、なので何もしなくてOK
    mov word[0x7c00],0xb200         ; 念のため別の値でもう一度確認
    cmp word[es:0x7c10],0xb200
    jne SetA20LineDone

    ; ここまで来たら「無効」と判定できたので、実際に有効化する。
    ; ポート0x92は「システムコントロールポートA」と呼ばれるハードウェアの
    ; 制御ポートで、bit1(値2)を立てるとA20ラインが有効になる。
    ; bit0は「立てるとCPUがリセットしてしまう」危険なビットなので、
    ; 誤って一緒に立ててしまわないようマスクしている。
    in al, 0x92
    or al, 2
    and al, 0xfe        ; bit0(高速リセット)は誤って立てない
    out 0x92, al

    ; 有効化できたか、もう一度同じ方法で確認する。
    mov word[0x7c00],0xd200
    cmp word[es:0x7c10],0xd200
    je A20Error          ; まだ折り返して見えるなら、有効化に失敗している

SetA20LineDone:
    xor ax,ax
    mov es,ax           ; ESを元(0)に戻しておく
    ; 進捗確認用に'A'(A20、有効化完了)を表示。
    mov ah, 0x0e
    mov al, 'A'
    int 0x10

    ; ========================================================================
    ; ステップ5: プロテクトモードへ切り替える準備
    ; ========================================================================
SetVideoMode:
    mov ax, 3    ; BIOSのビデオモード3番 = 80x25文字のテキストモード。
    int 0x10     ; 起動直後のモードをはっきりさせておくためのおまじない。

    cli   ; これ以降、割り込みに関する設定が全部変わるので、
          ; 全部の準備が整うまで割り込みを禁止しておく。
          ; (実際に割り込みを許可し直すのは、この後C言語側の
          ; enable_interrupts()が呼ばれるタイミング)

    ;global register
    lgdt [Gdt32Ptr]   ; GDT(後述)をCPUに登録する
    lidt [Idt32Ptr]   ; IDT(割り込みテーブル)は「まだ無い(空っぽ)」と登録する。
                      ; プロテクトモードのこの短い区間では割り込みを使わない
                      ; 前提なので、わざと空にしておいて、もし何か例外が
                      ; 起きたら派手に失敗するようにしている。

    ; CR0レジスタのbit0(PEビット)を立てると、その瞬間からCPUは
    ; プロテクトモードで動作するようになる。
    mov eax, cr0
    or eax, 1
    mov cr0, eax

    ; セグメント:オフセットではなく「セレクタ:オフセット」形式のjmpで、
    ; CSレジスタを32bitコードセグメント(セレクタ0x08、下のGdt32参照)に
    ; 切り替えながらProtectedModeStartへ飛ぶ。この命令が実行された瞬間に、
    ; CPUは名実ともに32bitプロテクトモードの命令の解釈を始める。
    jmp 0x08:ProtectedModeStart

; ============================================================================
; エラー処理(ここに来る経路はいろいろあるが、やることは同じ:停止するだけ)
; ============================================================================
ReadError:      ; ディスク読み込み失敗
NotSupport:     ; ロングモード非対応 or e820非対応
A20Error:       ; A20有効化失敗
End:
    hlt
    jmp End

; ============================================================================
; [BITS 32] ここから32bitプロテクトモードのコード
; ============================================================================
[BITS 32]
ProtectedModeStart:
    ; プロテクトモードでは、セグメントレジスタには「セグメントの実アドレス」
    ; ではなく、GDT(後述)の何番目の記述子を使うかを表す「セレクタ番号」を
    ; 入れる。0x10はGdt32の2番目のエントリ(Data32、フラットなデータ
    ; セグメント)を指す。
    mov ax, 0x10
    mov ds, ax
    mov es, ax
    mov ss, ax
    mov esp, 0x7c00

    ; 進捗確認用に、画面メモリへ直接'P'(Protected mode)を書き込む。
    ; プロテクトモードに入った直後はまだBIOSのint 0x10が使えないので、
    ; VGAテキストモードのメモリ(物理0xb8000番地から、2バイトで1文字。
    ; 1バイト目=文字コード、2バイト目=色)に直接書き込んでいる。
    mov byte [0xb8000], 'P'
    mov byte [0xb8001], 0xa

    ; --------------------------------------------------------------------
    ; ページテーブルの準備
    ; --------------------------------------------------------------------
    ; ロングモードでは必ずページング(仮想アドレス→物理アドレスの変換の
    ; 仕組み)を有効にする必要がある。ページテーブルは4階層(PML4→PDPT→
    ; PD→PT)が基本だが、ここでは「1GBページ」という特別な仕組みを使って
    ; PML4→PDPTの2階層だけで済ませている(PD・PTを省略できる代わりに、
    ; 1回のマッピングで1GBという大きな単位になる)。
    ;
    ; まず物理0x70000番地から0x10000バイト(64KB)分を0でクリアして、
    ; ページテーブル用の作業スペースを確保する。
    cld
    mov edi,0x70000
    xor eax,eax
    mov ecx,0x10000/4
    rep stosd

    ; --- マッピング1: 恒等(identity)マッピング ---
    ; 物理0x70000番地にPML4テーブルを置き、その1番目のエントリ(PML4[0])
    ; が物理0x71000番地のPDPTテーブルを指すようにする。
    ; さらにPDPT[0]を「1GBページ、物理0番地から」という設定にすることで、
    ; 「仮想アドレス0～1GB」=「物理アドレス0～1GB」というそのままの
    ; (恒等)マッピングができる。これがあるおかげで、ロングモードに
    ; 入った直後もこのコード自身(低いアドレスにある)が実行し続けられる。
    ;
    ; 各エントリの下位ビットは「フラグ」:
    ;   bit0(P)=1: このエントリは有効(Present)
    ;   bit1(W)=1: 書き込み可能(Writable)
    ;   bit2(U)=1: リング3(ユーザーモード)からもアクセス可能(User)
    ;   bit7(PS)=1: これは(PDPTレベルでは)1GBページである(Page Size)
    ; PDPT側(次の行)は元からUビット付きだったが、PML4側はP,Wのみで
    ; Uビットが無かった。両方揃わないとリング3からアクセスできない
    ; (実際にVGAメモリ0xb8010へのアクセスでページフォルトを踏んで気づいた)。
    mov dword[0x70000],0x71007   ; PML4[0] → 0x71000番地のPDPTを指す (P,W,U)
    mov dword[0x71000],10000111b ; PDPT[0]: Present, Writable, User, PS=1 → 物理0番地から1GBを恒等マッピング

    ; --- マッピング2: higher-half(上位アドレス)マッピング ---
    ; カーネル本体は仮想アドレスの「上位半分」の始まり、
    ; 0xffff800000000000(KERNEL_BASEと呼んでいる値)から実行される設計
    ; になっている(link.lds参照)。このアドレスが実際にどのPML4の
    ; 何番目のエントリに対応するかを計算する。
    mov eax,(0xffff800000000000 >> 39)  ; PML4のインデックスは仮想アドレスの
    and eax,0x1ff                        ; bit47-39の9bit。計算すると256になる。
    ; U(ユーザー)ビットをPML4・PDPTの両方に立てる。カーネル本体もこの1GBに
    ; 乗っているので、リング3からカーネルのメモリも読み書きできてしまう
    ; (本来はユーザー用に別途小さな領域を分けるべきだが、今回はリング3への
    ; 切り替え自体を動かすことを優先した最小構成)。
    mov dword[0x70000 + eax*8],0x72007   ; PML4[256] → 0x72000番地のPDPTを指す (P,W,U)
    mov dword[0x72000],10000111b         ; PDPT[0]: P,W,U,PS=1 → 物理0番地から1GBをKERNEL_BASEへマッピング
    ; つまり「仮想アドレス0xffff800000000000～+1GB」も「物理アドレス
    ; 0～1GB」にマッピングされる。同じ物理メモリに、低いアドレスと
    ; 高いアドレスの2通りの名前(仮想アドレス)が付いている状態。

    ; CPUに「ページテーブルはこのGDT(64bit用)を使う」と登録しておく
    ; (実際にページングを有効にするのはこの後)。
    lgdt [Gdt64Ptr]

    ; CR4レジスタのbit5(PAEビット)を立てる。PAE(物理アドレス拡張)は
    ; ページングの内部構造を変える設定で、ロングモードを使うには
    ; 必ず先に有効にしておく必要がある。
    mov eax,cr4
    or eax,(1<<5)
    mov cr4,eax

    ; CR3レジスタに、さっき組み立てたPML4テーブルの物理アドレスを設定。
    ; これでCPUは「ページングを有効にしたら、このテーブルを使って
    ; アドレス変換してね」と分かる。
    mov eax,0x70000
    mov cr3,eax

    ; EFER(拡張機能レジスタ)のLMEビット(bit8)を立てる。
    ; MSR(モデル固有レジスタ)は普通のレジスタと違い、rdmsr/wrmsr命令で
    ; ECXに「どのMSRか」の番号を指定して読み書きする。0xc0000080がEFER。
    mov ecx,0xc0000080
    rdmsr
    or eax,(1<<8)
    wrmsr

    ; 最後にCR0のbit31(PGビット、ページング有効化)を立てる。
    ; PAE有効・LME有効・CR3設定済みの状態でこれを立てた瞬間、CPUは
    ; 正式にロングモード(64bit)へ切り替わる。
    ; (立てる順番が重要: CR4.PAE → CR3設定 → EFER.LME → CR0.PGの順で
    ; ないと仕様違反になる)
    mov eax,cr0
    or eax,(1<<31)
    mov cr0,eax

    ; ロングモードへの切り替えが完了したので、セレクタ0x8(64bitコード
    ; セグメント、下のGdt64参照)を使ってLongModeStartへジャンプ。
    jmp 0x8:LongModeStart

PEnd:
    hlt
    jmp PEnd

; ============================================================================
; [BITS 64] ここから64bitロングモードのコード
; ============================================================================
[BITS 64]
LongModeStart:
    ; SS/DS/ESを、今使っているGdt64(下で定義)のデータセグメント
    ; (セレクタ0x10)へ明示的に読み直す。ロングモードではセグメントの
    ; ベースアドレス自体は無視される(フラットなアドレス空間)が、
    ; どのセレクタが読み込まれているかという情報自体はCPU内部に
    ; キャッシュされて残る。ここで読み直しておかないと、後でこの
    ; セレクタ番号の意味が変わったとき(実際、kernel.asm側では0x10は
    ; 別の意味になる)に、割り込みからの復帰時などに不整合を起こす
    ; 可能性があるため、念のため明示的に統一しておく。
    mov ax, 0x10
    mov ds, ax
    mov es, ax
    mov ss, ax
    mov rsp, 0x7c00

    ; 進捗確認用に'L'(Long mode)を画面メモリへ直接書き込む。
    mov byte [0xb8000], 'L'
    mov byte [0xb8001], 0xa

    ; --------------------------------------------------------------------
    ; カーネル本体を、本来の実行場所へコピーする
    ; --------------------------------------------------------------------
    ; さっき(ステップ2で)物理0x10000番地に読み込んでおいたkernel.binを、
    ; カーネルが実際にリンクされている物理アドレス0x200000番地へコピー
    ; する。rep movsqは「RSIが指す場所からRDIが指す場所へ、RCX個の
    ; 8バイト単位のデータをコピーする」命令。
    cld
    mov rdi,0x200000    ; コピー先
    mov rsi,0x10000      ; コピー元
    mov rcx,(KERNEL_SECTORS*512)/8  ; コピーする量(8バイト単位の個数)。
                                    ; KERNEL_SECTORSは上で読み込んだ量と
                                    ; 同じ定数を使っているので、
                                    ; 「読み込んだ量」と「コピーする量」が
                                    ; 必ず一致する。
    rep movsq

    ; カーネルの本来のエントリポイント(仮想アドレス、higher-half側)へ
    ; ジャンプする。ここから先はkernel.asmの世界。このloader.asmの
    ; 役目はここで終わり。
    mov rax,0xffff800000200000
    jmp rax

LEnd:
    hlt
    jmp LEnd

; ============================================================================
; データ領域
; ============================================================================
DriveId:    db 0             ; ドライブ番号(boot.asmから引き継いだ値)
ReadPacket: times 16 db 0    ; カーネル読み込み用のDAP(16バイト)

; --- プロテクトモード用の一時的なGDT ---
; GDT(Global Descriptor Table)は「メモリのどの範囲を、どういう権限で
; 使えるか」を定義したテーブル。セグメントレジスタに入れるセレクタ番号は
; 「このテーブルの何番目を使うか」を表すインデックスになっている。
; このGdt32は、プロテクトモードのごく短い区間だけで使う一時的なもの。
Gdt32:
    dq 0        ; 1番目(セレクタ0x00)は必ず「ヌルディスクリプタ」。
                ; 仕様上、使ってはいけない予約領域。
Code32:         ; 2番目(セレクタ0x08): コードセグメント
    dw 0xffff   ; リミット(範囲)の下位16bit
    dw 0        ; ベースアドレスの下位16bit
    db 0        ; ベースアドレスの次の8bit
    db 0x9a     ; アクセスバイト: Present, リング0, 実行可能, など
    db 0xcf     ; リミット上位4bit + フラグ(4GB全体をカバーするフラット
                ; セグメントにするための設定)
    db 0        ; ベースアドレスの最上位8bit
Data32:         ; 3番目(セレクタ0x10): データセグメント
    dw 0xffff
    dw 0
    db 0
    db 0x92     ; アクセスバイト: Present, リング0, 書き込み可能なデータ
    db 0xcf
    db 0

Gdt32Len equ $-Gdt32   ; Gdt32全体のバイト数を自動計算

Gdt32Ptr: dw Gdt32Len -1   ; CPUに渡す「GDTの場所」の情報。
          dd Gdt32          ; limit(サイズ-1)とbaseアドレスのペア。
                            ; lgdt命令はこの形式のデータを読む。

Idt32Ptr: dw 0    ; IDT(割り込みテーブル)の情報。limit=0, base=0という
          dd 0    ; 「空っぽ」の状態を登録している(ステップ5のコメント参照)。

; --- ロングモード用の一時的なGDT ---
; ロングモードでは(64bit全体をフラットに使うので)ベースアドレスや
; リミットの値自体にほとんど意味が無く、大幅にシンプルになる。
Gdt64:
    dq 0                     ; ヌルディスクリプタ(セレクタ0x00)
    dq 0x0020980000000000   ; コードセグメント (L=1, 64bit) (セレクタ0x08)
    dq 0x0000920000000000   ; データセグメント (セレクタ0x10)
Gdt64Len equ $-Gdt64

Gdt64Ptr: dw Gdt64Len -1
             dq Gdt64
