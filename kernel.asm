; ============================================================================
; kernel.asm — カーネル本体の入口(C言語のKMainを呼ぶ前の下ごしらえ)
; ============================================================================
; loader.asmが物理アドレス0x200000にこのファイルを読み込んだ後、
; higher-half(仮想アドレス0xffff800000200000)へジャンプしてくる。
; C言語のKMain()はまだ何も知らない(GDT/TSS/割り込みコントローラなどの
; 設定が済んでいない)状態なので、ここで一通りの下ごしらえをしてから
; KMain()へ処理を渡す。
;
; やっていることを順番に並べると:
;   1. このファイル自身のGDT(セグメント定義)を読み込む
;   2. TSS(タスク状態セグメント、割り込み時のスタック切り替えに使う)を用意する
;   3. PIT(タイマー)とPIC(割り込みコントローラ)を初期化する
;   4. C言語のKMain()を呼ぶ
;   5. (KMain側からenter_usermode()が呼ばれたら)UserEntryでリング3の
;      デモコードを実行する
; ============================================================================

section .data

; ============================================================================
; GDT (Global Descriptor Table) — このカーネル専用のセグメント定義
; ============================================================================
; loader.asmにも似たようなGdt64があったが、あちらはロングモードへ
; 切り替える一瞬だけ使う仮のもの。ここからは、このGdt64が本番の
; セグメントテーブルになる。
;
; セレクタ番号(0x08/0x10/0x18/0x20)はこのファイル内でのみ有効。loader.asmが
; ロングモード移行に使う一時的なGdt64とは無関係で、ここに来た時点で
; lgdtにより完全に置き換わっている(loader.asm側の0x10はデータセグメント
; だが、こちらの0x10はリング3のコードセグメントであり意味が異なる)。
;
; 各エントリは8バイトの「セグメントディスクリプタ」。64bitモードでは
; ベースアドレスやリミットの値自体はほとんど意味を持たない(フラットな
; アドレス空間を使うため)。重要なのは主に2箇所:
;   ・アクセスバイト(下から数えて5バイト目)の中の DPL(権限レベル、
;     0=カーネル/3=ユーザー) と、コードかデータか・実行可能かどうか
;   ・フラグニブル(6バイト目の上位4bit)の中の L(Long、64bitコード
;     セグメントかどうか)
Gdt64:
    dq 0                     ; セレクタ0x00: ヌルディスクリプタ(仕様上の
                              ; 予約領域、使ってはいけない)
    dq 0x0020980000000000    ; 0x08: カーネル(リング0)コードセグメント
                              ;   アクセスバイト0x98 = Present,DPL0,実行可能
                              ;   フラグ0x2の上位ビット = L=1(64bitコード)
    dq 0x0020f80000000000    ; 0x10: ユーザー(リング3)コードセグメント
                              ;   アクセスバイト0xf8 = Present,DPL3,実行可能
    dq 0x0000f20000000000    ; 0x18: ユーザー(リング3)データセグメント
                              ;   アクセスバイト0xf2 = Present,DPL3,書き込み可
    dq 0x0000920000000000    ; 0x20: カーネル(リング0)データセグメント
                              ;   アクセスバイト0x92 = Present,DPL0,書き込み可
TssDesc:
    ; TssDescはGDTの一部だが、他の8バイトのエントリと違い、64bitモードの
    ; TSSディスクリプタは16バイト(GDTの2エントリ分)を使う特別な形式。
    ; TSS自体の物理アドレス(下のTssラベルの場所)をこの中に埋め込む
    ; 必要があるが、アセンブラのequ計算だけでは綺麗に書けないバイト配置
    ; なので、下のSetTss:で実行時に値を計算して書き込んでいる。
    ; ここではその「入れ物」だけを用意している。
    dw TssLen-1   ; リミット(TSSのサイズ-1)。アセンブル時点で計算できるので先に書ける
    dw 0          ; ベースアドレス下位16bit ← 実行時にSetTssが書き込む
    db 0          ; ベースアドレス次の8bit   ← 同上
    db 0x89       ; タイプ: 64bit TSS(使用可能)、Present
    db 0          ; リミット上位4bit+フラグ
    db 0          ; ベースアドレス次の8bit  ← 実行時にSetTssが書き込む
    dq 0          ; ベースアドレス残り32bit + 予約 ← 実行時にSetTssが書き込む

Gdt64Len: equ $-Gdt64   ; GDT全体のバイト数(TssDescの16バイトも含む)

Gdt64Ptr: dw Gdt64Len-1   ; lgdt命令に渡す「limit(サイズ-1)とbaseアドレス」のペア
          dq Gdt64

; ============================================================================
; ダブルフォルト専用の緊急スタック(IST1)
; ============================================================================
; DFStack: times 4096 db 0   ; ダブルフォルト(ベクタ8)専用のIST1スタック。
; DFStackTop:                ; スタック自体が壊れて起きるダブルフォルトを、同じ壊れた
;                            ; スタックのまま処理しようとして連鎖的にトリプルフォルト
;                            ; するのを防ぐため、専用の領域を別に用意しておく。
;
; 「IST(Interrupt Stack Table)」は、TSSの中にある最大7個までの
; 「緊急用スタックのアドレス」のリスト。通常の割り込み・例外は、
; 割り込まれた時点のスタックをそのまま使うが、IDT側で「この例外は
; IST番号Nの緊急スタックを使う」と指定しておくと、その例外が起きた
; 瞬間に強制的にそのスタックへ切り替えてくれる。
; ダブルフォルト(スタックが壊れているせいで起きることが多い例外)に
; これを使わないと、壊れたスタックのままハンドラを動かそうとして、
; さらに失敗して……という連鎖(最終的にCPUがリセットする「トリプル
; フォルト」)になりやすい。専用の綺麗なスタックを別に確保しておけば、
; その問題を避けられる。
DFStack: times 4096 db 0   ; ダブルフォルト(ベクタ8)専用のIST1スタック。
DFStackTop:                ; スタック自体が壊れて起きるダブルフォルトを、同じ壊れた
                            ; スタックのまま処理しようとして連鎖的にトリプルフォルト
                            ; するのを防ぐため、専用の領域を別に用意しておく。
                            ; (スタックはアドレスの高い方から低い方へ伸びるので、
                            ;  「スタックの先頭」として使うのは確保した領域の
                            ;  終わり=DFStackTopの方)

; ============================================================================
; リング3デモ用のスタック
; ============================================================================
UserStack: times 4096 db 0 ; リング3デモ用のスタック。C側からenter_usermode()の
UserStackTop:               ; 引数として渡す。(DFStackと同じ理由で、使うのは
                            ; 「終わり」の方=UserStackTop)

; ============================================================================
; TSS (Task State Segment)
; ============================================================================
; 64bitモードのTSSは、本来の「タスク切り替え」機能としてはもう使われて
; いない(古い32bit時代の名残)。今のCPUで実際に使われているのは主に
; 2つの役割:
;   ・RSP0: リング3(ユーザーモード)を実行中に割り込み/例外が発生した時、
;           自動的に切り替える先のカーネル用スタックポインタ
;   ・IST1-7: 特定の例外専用の緊急スタック(上のDFStack参照)
; TSSのバイト配置は仕様で厳密に決まっている(下のコメントに実際の
; オフセットを書いてある)。
Tss:
    dd 0                    ; オフセット0-3: 予約(未使用)
    dq 0xffff800000190000   ; オフセット4-11: RSP0。
                             ; リング3からの割り込み/例外時にロードするカーネル
                             ; スタック。物理0x190000はkalloc()が&end(カーネル本体の
                             ; 終端、2MB以降)より前を配らないため今のところ衝突しない。
    times 24 db 0            ; オフセット12-35: RSP1, RSP2, 予約(いずれも未使用)
    dq DFStackTop            ; オフセット36-43: IST1。
                              ; ダブルフォルト用スタック(上のDFStackTop)
    times 48 db 0             ; オフセット44-91: IST2-7(未使用、6個×8バイト)
    times 8 db 0               ; オフセット92-99: 予約(未使用)
    dw 0                        ; オフセット100-101: 予約領域(仕様上ゼロでなければならない)
    dw TssLen                   ; オフセット102-103: I/Oマップベースアドレス。
                                 ; TSSリミット(TssLen-1)より大きい値にすることで、
                                 ; I/O許可ビットマップ無し(リング3からの生ポート
                                 ; 入出力は全部例外)を明示する

TssLen: equ $-Tss   ; TSS全体のバイト数(仕様上104バイトになるはず)

section .text
extern KMain      ; main.cで定義されているKMain()関数(C言語側)
global start       ; loader.asmから見える、このファイルの開始位置
global UserEntry    ; main.cから見える、リング3デモの開始位置
global UserStackTop  ; main.cから見える、リング3デモ用スタックの先頭アドレス

; ============================================================================
; start — このファイルの実行開始位置
; ============================================================================
start:
    ; このカーネル専用のGdt64を実際にCPUへ登録する。loader.asm側の
    ; 一時的なGDTから、ここで正式なGDTへ切り替わる。
    mov rax, Gdt64Ptr
    lgdt [rax]

    ; SS/DS/ESはloader.asmの一時的なGdt64から読み込まれた値のまま残っている。
    ; loader.asm側の0x10はデータセグメントだったが、上でロードしたこちらの
    ; Gdt64では0x10はリング3コードセグメントなので、SSにコードセグメントが
    ; 乗ったまま割り込みが発生するとiretqのSS再ロードで#GPになる
    ; (実際に割り込みを有効化した際に踏んだ)。ここで明示的に読み直す。
    mov ax, 0x20
    mov ss, ax
    mov ds, ax
    mov es, ax

; ============================================================================
; SetTss — TSSディスクリプタにTSSの実アドレスを書き込み、CPUに登録する
; ============================================================================
SetTss:
    ; TssDesc(上で定義した16バイトの入れ物)の中に、Tssラベルの実際の
    ; アドレスをバイト単位で切り分けて書き込んでいく。64bit TSS
    ; ディスクリプタのベースアドレスは、仕様上バイト位置が飛び飛びに
    ; なっている変な配置なので、シフト演算で少しずつ取り出しながら
    ; 該当バイトへ書き込む、という手順になる。
    mov rax,Tss
    mov rdi,TssDesc
    mov [rdi+2],ax     ; ベースアドレスの下位16bit → オフセット2-3へ
    shr rax,16
    mov [rdi+4],al      ; 次の8bit → オフセット4へ
    shr rax,8
    mov [rdi+7],al       ; さらに次の8bit → オフセット7へ(6は別項目なので飛ばす)
    shr rax,8
    mov [rdi+8],eax        ; 残り32bit(上位アドレス全部) → オフセット8-11へ

    ; ltr(Load Task Register)命令で、「TSSはセレクタ0x28(GDTの6番目、
    ; TssDescの位置)にある」とCPUに教える。これでRSP0/IST1などが
    ; 実際に使われるようになる。
    mov ax,0x28
    ltr ax

; ============================================================================
; InitPIT — PIT(Programmable Interval Timer)を初期化する
; ============================================================================
; PITは一定間隔でIRQ0(タイマー割り込み)を発生させ続けてくれるハード
; ウェア。これが無いと、CPUは「今どれくらい時間が経ったか」を知る
; 手段が無く、後でスケジューラ(複数のプログラムを切り替えて実行する
; 仕組み)を作るときにも困る。
InitPIT:
    ; PITへのコマンドはポート0x43に1バイト書き込む形式。
    ; (1<<2)|(3<<4) を2進数で見ると 00110100 になり、内訳は:
    ;   bit7-6=00: チャンネル0を選択
    ;   bit5-4=11: 読み書きは「下位バイト→上位バイト」の順
    ;   bit3-1=010: モード2(レートジェネレータ、指定した周期で
    ;               繰り返しパルスを出す)
    ;   bit0=0: 2進数モード(BCDではない)
    mov al,(1<<2)|(3<<4)  ; channel0, lobyte/hibyte, mode2(rate generator), binary
    out 0x43,al

    ; 周期を決める「分周値」を設定する。PITの元となるクロックは
    ; 1193182Hzで固定なので、1193182 ÷ 分周値 = 実際の割り込み周波数。
    ; 11931を指定すると、1193182/11931 ≈ 100Hz、つまり1秒間に約100回
    ; タイマー割り込みが発生するようになる。
    ; コマンドで「下位バイト→上位バイト」の順と指定したので、
    ; 先にAL(下位8bit)、次にAH(上位8bit)の順で書き込む。
    mov ax,11931
    out 0x40,al
    mov al,ah
    out 0x40,al

; ============================================================================
; InitPIC — PIC(8259互換 割り込みコントローラ)を初期化する
; ============================================================================
; PICは、キーボードやタイマーなどのハードウェアからの割り込み要求
; (IRQ)を受け取り、CPUへ伝える橋渡し役。PC/AT互換機には2個のPIC
; (マスタ・スレーブ)がカスケード接続されている。
; 起動直後のPICは、リアルモード用の古い割り込み番号(0-15)にそのまま
; つながっているが、それではCPUの例外番号(0-31)と衝突してしまうので、
; 「ICW(Initialization Command Word)」という一連のコマンドを送って、
; 割り込み番号を32番以降に付け替える「リマップ」という作業が必要。
InitPIC:
    ; ICW1: 初期化開始の合図。0x11 = 「これから初期化する、ICW4も送る」
    mov al,0x11
    out 0x20,al   ; マスタPIC
    out 0xa0,al   ; スレーブPIC

    ; ICW2: このPICが担当するIRQを、CPUの割り込み番号の何番から
    ; 始めるか。マスタは32番から(IRQ0→ベクタ32)、スレーブは40番から
    ; (IRQ8→ベクタ40)に割り当てる。
    mov al,32
    out 0x21,al
    mov al,40
    out 0xa1,al

    ; ICW3: マスタとスレーブがどう繋がっているかを教える。
    ; マスタ側には「IRQ2(bit2、値4)にスレーブが繋がっている」、
    ; スレーブ側には「自分はマスタのIRQ2に繋がっている(識別番号2)」
    ; と設定する。
    mov al,4
    out 0x21,al
    mov al,2
    out 0xa1,al

    ; ICW4: 動作モードの指定。1 = 8086/88モード(今のPCでは基本これ)
    mov al,1
    out 0x21,al
    out 0xa1,al

    ; OCW1(割り込みマスクレジスタ): 各bitが0のIRQだけが有効になる。
    ; マスタは 11111110b → bit0(IRQ0=タイマー)だけ有効、残りは無効。
    ; スレーブは 11111111b → 全部無効(今はまだ何も使わない)。
    mov al,11111110b
    out 0x21,al
    mov al,11111111b
    out 0xa1,al

    ; --------------------------------------------------------------------
    ; C言語側(KMain)へ処理を渡す
    ; --------------------------------------------------------------------
    ; 「retf(far return)」は本来、call命令で積まれたリターンアドレスを
    ; 使って戻るための命令だが、ここではスタックに自分でCS(セレクタ8)
    ; とRIP(KernelEntryのアドレス)を積んでからretfを実行することで、
    ; 「CSを読み直しながら任意の場所へジャンプする」という、jmp far と
    ; 同じ効果を作り出している(64bitモードでは immediate 値を使った
    ; 直接のfar jmpが書きにくいための、よくある回避テクニック)。
    ; db 0x48 は「REX.Wプレフィックス」という、次の命令(retf)を
    ; 64bit幅で動かすための1バイトを直接書き込んでいる
    ; (NASMのバージョンによってはretfqのように書けないことがあるため)。
    mov rax, KernelEntry
    push 8        ; 積む順番はiretq/retfの仕様上、後で読み出す順の逆。
    push rax      ; 先にCS、次にRIPを積む
    db 0x48       ; REX.Wプレフィックス(次のretfを64bit幅にする)
    retf          ; RIP=KernelEntry, CS=8 として、KernelEntryへジャンプ

; ============================================================================
; KernelEntry — C言語のKMain()を呼び出す
; ============================================================================
KernelEntry:
    ; C言語の関数を呼ぶ前に、ちゃんとしたスタックポインタを設定して
    ; おく必要がある。カーネル自身のロード先アドレス(0xffff800000200000)
    ; をそのままスタックの初期位置として使っている(スタックは下方向に
    ; 伸びるので、この番地より下の、まだ何も置かれていない領域を使う)。
    mov rsp,0xffff800000200000
    call KMain

    ; KMain()は通常、enter_usermode()を呼んでリング3へ制御を渡すので
    ; ここには戻ってこない想定だが、万が一戻ってきた場合や、KMain内で
    ; ASSERT失敗などにより異常終了した場合の保険として、CPUを停止させて
    ; おくループを用意している。
End:
    hlt
    jmp End

; ============================================================================
; UserEntry — リング3(ユーザーモード)で実際に動くことを示す最小限のデモ
; ============================================================================
; C言語側のKMainの最後からenter_usermode()(trap.asm参照)経由でここへ
; 飛んでくる。ここに来た時点で、CPUの権限レベルはリング0(カーネル)
; からリング3(ユーザー)に変わっている。
; やっていることは「画面のある1バイトを無限にインクリメントし続ける」
; だけ。これだけの単純な処理でも、値が絶えず変わり続けている様子が
; 画面で確認できれば、「リング3への切り替えが成功していて、かつ
; タイマー割り込みに邪魔されながらも処理を継続できている」ことの
; 分かりやすい証拠になる。
UserEntry:
    inc byte [0xb8010]    ; VGAテキストメモリの1バイトを+1する。
                           ; 0xb8010は画面の1行目、9文字目の位置。
    mov byte [0xb8011], 0xf  ; その文字の色を白(0xf)に固定しておく
    jmp UserEntry             ; 永遠にこれを繰り返す
