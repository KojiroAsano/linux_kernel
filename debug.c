#include "debug.h"
#include "print.h"

// ============================================================================
// error_check — ASSERTが失敗した時に呼ばれる、エラー報告処理
// ============================================================================
// debug.hのASSERTマクロから、条件が偽だった時にだけ呼ばれる。
// 「目立つ見た目の枠」+「どのファイルの何行目か」を画面に表示してから、
// 無限ループ(while(1){})でCPUを止める。
//
// 【注意】ここでは割り込みを止めていない(cli していない)。もし
// 割り込みが有効な状態でここに来ると、この無限ループの最中も
// タイマー割り込みなどは引き続き発生し、処理され続ける(trap.cの
// handler()が動く)。画面表示や停止そのものには影響しないが、
// 「完全に何も起きていない状態で止まっている」わけではない、
// という点は覚えておくとよい。
void error_check(char *file, uint64_t line)
{
    printk("\n------------------------------------------\n");  // 上の区切り線
    printk("             ERROR CHECK");                          // 見出し
    printk("\n------------------------------------------\n");     // 下の区切り線
    printk("Assertion Failed [%s:%u]", file, line);   // %s=ファイル名, %u=行番号

    while (1) { }   // ここから先には進まない。これ以上コードを実行させず、
                     // 今表示した内容を画面に残したまま停止させる。
}
