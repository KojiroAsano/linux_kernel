; ============================================================================
; start.asm — ユーザープログラムの本当のエントリポイント
; ============================================================================
; process.cのset_process_entry()が、このプロセスのtf->ripを0x400000
; (link.ldsで指定した、このプログラムのロードベースアドレス)に
; 設定するので、リング3へ切り替わった瞬間、CPUは必ずこのstart:から
; 実行を始める。main()を呼び、万が一main()がreturnしてきても
; (自分でexitu()を呼び忘れた場合の保険として)確実にプロセスが
; 終了するようにしている。
; ============================================================================

section .text
global start
extern main
extern exitu

start:
    call main    ; main.cのmain()を呼ぶ
    call exitu    ; main()が戻ってきたら、忘れずプロセスを終了させる
    jmp $          ; ここには来ないはずだが、念のため停止しておく
